#!/usr/bin/env python3
"""Write webapp/src/fontPreviews.ts: one PNG per caption font, drawn by the
same code and in the same colours the hosted clips use, so the web app's
font picker previews exactly what will render.

    python3 scripts/font_previews.py

Rerun after changing engine/caption_fonts.py or the hosted caption colours.
"""
import base64
import io
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT))

from PIL import Image, ImageDraw  # noqa: E402

from engine import caption_colour as cc, caption_fonts as cf  # noqa: E402
from pipeline.core import STYLE  # noqa: E402

W, H, SIZE = 720, 150, 78
fill, emph = cc.rgba(STYLE["caption_fill"]), cc.rgba(STYLE["caption_emph"])
out = ["// Generated by scripts/font_previews.py. Do not edit by hand.",
       "export const FONT_PREVIEWS: Record<string, string> = {"]
for k in cf.FONTS:
    f = cf.face(k, SIZE)
    sw = max(4, int(SIZE * cf.FONTS[k][3] * 0.10))
    im = Image.new("RGBA", (W, H), (28, 32, 38, 255))
    d = ImageDraw.Draw(im)
    words = [("that was", fill), ("insane", emph)]
    total = sum(d.textlength(w, font=f) for w, _ in words) + d.textlength(" ", font=f) + 2 * sw
    x = (W - total) / 2
    for word, col in words:
        d.text((x, H / 2), word, font=f, fill=col, stroke_width=sw,
               stroke_fill=(0, 0, 0, 255), anchor="lm")
        x += d.textlength(word + " ", font=f) + sw
    buf = io.BytesIO()
    im.convert("RGB").save(buf, "PNG", optimize=True)
    out.append(f'  {k}: "{base64.b64encode(buf.getvalue()).decode()}",')
out.append("};")
(ROOT / "webapp/src/fontPreviews.ts").write_text("\n".join(out) + "\n")
print(f"wrote {len(cf.FONTS)} previews, {sum(len(l) for l in out) // 1024} KB")

#!/usr/bin/env python3
"""Write webapp/src/fontPreviews.ts: caption preview layers for every font,
drawn by the same code the hosted clips use, so the web app's picker previews
exactly what will render.

    python3 scripts/font_previews.py

Each font gets three alpha masks of the sample line "that was insane": the
black stroke under both words, the fill of the body words, and the fill of
the highlighted word. The web app stacks them with CSS masks and paints each
fill in the colour picked, so any font and colour pair previews without a
PNG per combination.

Rerun after changing engine/caption_fonts.py.
"""
import base64
import io
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT))

from PIL import Image, ImageDraw  # noqa: E402

from engine import caption_fonts as cf  # noqa: E402

W, H, SIZE = 720, 150, 78
WORDS = ("that was", "insane")


def png(im: Image.Image) -> str:
    buf = io.BytesIO()
    im.save(buf, "PNG", optimize=True)
    return base64.b64encode(buf.getvalue()).decode()


out = ["// Generated by scripts/font_previews.py. Do not edit by hand.",
       "export const FONT_PREVIEWS: Record<string, { stroke: string; body: string; emph: string }> = {"]
for k in cf.FONTS:
    f = cf.face(k, SIZE)
    sw = max(4, int(SIZE * cf.FONTS[k][3] * 0.10))
    layers = {n: Image.new("RGBA", (W, H), (0, 0, 0, 0)) for n in ("stroke", "body", "emph")}
    probe = ImageDraw.Draw(layers["stroke"])
    total = sum(probe.textlength(w, font=f) for w in WORDS) + probe.textlength(" ", font=f) + 2 * sw
    x = (W - total) / 2
    for word, fill in zip(WORDS, ("body", "emph")):
        ImageDraw.Draw(layers["stroke"]).text((x, H / 2), word, font=f, fill=(0, 0, 0, 255),
                                              stroke_width=sw, stroke_fill=(0, 0, 0, 255), anchor="lm")
        ImageDraw.Draw(layers[fill]).text((x, H / 2), word, font=f, fill=(255, 255, 255, 255), anchor="lm")
        x += probe.textlength(word + " ", font=f) + sw
    out.append(f"  {k}: {{ " + ", ".join(f'{n}: "{png(im)}"' for n, im in layers.items()) + " },")
out.append("};")
(ROOT / "webapp/src/fontPreviews.ts").write_text("\n".join(out) + "\n")
print(f"wrote {len(cf.FONTS)} fonts x 3 layers, {sum(len(line) for line in out) // 1024} KB")
